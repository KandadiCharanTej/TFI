// Helper functions for content retrieval
export function getTeluguMovieById(id: string): TeluguMovie | undefined {
  return TELUGU_CINEMA_DATABASE.find(m => m.id === id);
}

export function getHeadSetGoDeck(category?: string): TeluguMovie[] {
  if (!category || category === 'all') return TELUGU_CINEMA_DATABASE;
  return TELUGU_CINEMA_DATABASE.filter(m => m.headSetGoCategory === category);
}

export function getTransifyDeck(category?: string, difficulty?: string): TeluguMovie[] {
  return TELUGU_CINEMA_DATABASE.filter(m => {
    if (!m.transifyPrompt) return false;
    if (category && category !== 'all' && m.transifyPrompt.category !== category) return false;
    if (difficulty && difficulty !== 'all' && m.transifyPrompt.difficulty !== difficulty) return false;
    return true;
  });
}

export function getCharadesDeck(difficulty?: string): TeluguMovie[] {
  return TELUGU_CINEMA_DATABASE.filter(m => {
    if (difficulty && difficulty !== 'all' && m.charadesDifficulty !== difficulty) return false;
    return true;
  });
}

export function getEmojiCinemaDeck(difficulty?: string): TeluguMovie[] {
  return TELUGU_CINEMA_DATABASE.filter(m => {
    if (!m.emojiClue) return false;
    if (difficulty && difficulty !== 'all' && m.emojiClue.difficulty !== difficulty) return false;
    return true;
  });
}

export function getAuctionLotsPool(pool: 'balanced' | 'nostalgia' | 'tier1' | 'chaos', limit = 12): TeluguMovie[] {
  let filtered = TELUGU_CINEMA_DATABASE.filter(m => Boolean(m.auctionLot));
  if (pool !== 'balanced') {
    filtered = filtered.filter(m => m.auctionLot?.pool === pool || m.auctionLot?.pool === 'chaos');
  }
  // Shuffle and slice
  const shuffled = [...filtered].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, limit);
}
